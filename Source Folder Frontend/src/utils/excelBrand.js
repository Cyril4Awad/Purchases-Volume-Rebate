import ExcelJS from "exceljs";
import { saveAs } from "file-saver";
import moment from "moment";
import { loadCompanyLogo } from "./appSettings";

/*
 * Branded Excel sheets for every export: the company logo (COm_Logo) top left, the title
 * centred over the sheet, then sections and grid tables in the palette (blue for
 * table headers, green for section bands and totals).
 *
 *   const { wb, ws, cursor } = await startSheet({ title, subtitle, columns: [{ width }...] });
 *   cursor.section("Fees");
 *   cursor.table([{ header, key, num }], rows, { totals });
 *   cursor.fields([["Reference", "CT-1"], ...]);
 *   await saveWorkbook(wb, "file name");
 */

export const BRAND = {
    blue: "155DFC",
    blueDark: "1C398E",
    blueSoft: "EFF6FF",
    green: "00A63E",
    greenDark: "016630",
    greenSoft: "DCFCE7",
    text: "101828",
    muted: "6A7282",
    border: "D1D5DC",
    zebra: "F9FAFB",
    labelBg: "F3F4F6",
    white: "FFFFFF",
};

const argb = (hex) => `FF${hex}`;
const solid = (hex) => ({ type: "pattern", pattern: "solid", fgColor: { argb: argb(hex) } });
const thin = (hex = BRAND.border) => ({ style: "thin", color: { argb: argb(hex) } });
export const gridBorder = (hex) => ({ top: thin(hex), left: thin(hex), bottom: thin(hex), right: thin(hex) });
const FONT = "Calibri";

/**
 * "1,234.56" (optionally followed by a currency) as a number with its number format, so Excel
 * can add it up; null when the text isn't a plain amount (percentages, labels, dates).
 */
export function toExcelNumber(value) {
    if (typeof value === "number") return { value, numFmt: "#,##0.00" };
    const m = /^(-?[\d,]+)(?:\.(\d+))?(?:\s+[A-Z]{3})?$/.exec(String(value ?? "").trim());
    if (!m) return null;
    const decimals = m[2]?.length ?? 0;
    return {
        value: Number(`${m[1].replace(/,/g, "")}${m[2] ? `.${m[2]}` : ""}`),
        numFmt: decimals ? `#,##0.${"0".repeat(decimals)}` : "#,##0",
    };
}

const userName = () => {
    try {
        const u = JSON.parse(localStorage.getItem("userData") ?? "null");
        return u?.userName || u?.userCode || "";
    } catch { return ""; }
};

const companyName = () => {
    try { return JSON.parse(sessionStorage.getItem("companyInfo") ?? "null")?.name ?? ""; } catch { return ""; }
};

/**
 * New workbook with one branded sheet. columns: [{ width }] fixes the grid every section
 * and table is laid out on (tables use the first N columns; merged cells span the rest).
 */
export async function startSheet({ title, subtitle, sheetName = "Sheet1", columns, landscape = true }) {
    const wb = new ExcelJS.Workbook();
    wb.creator = "Sales Volume Rebate";
    wb.created = new Date();
    const ws = wb.addWorksheet(sheetName.slice(0, 31).replace(/[\\/?*[\]:]/g, "-"), {
        views: [{ showGridLines: false }],
        pageSetup: { orientation: landscape ? "landscape" : "portrait", fitToPage: true, fitToWidth: 1, fitToHeight: 0, paperSize: 9 },
    });
    const width = columns.length;
    ws.columns = columns.map((c) => ({ width: c.width ?? 16 }));

    // rows 1-3: the logo alone, top left; the text block sits below it so a narrow sheet
    // never puts the title under the logo
    const logo = await loadCompanyLogo().catch(() => null);
    let row = 1;
    if (logo) {
        [1, 2, 3].forEach((r) => { ws.getRow(r).height = 18; });
        const id = wb.addImage({ base64: logo.dataUrl, extension: "png" });
        const ratio = logo.width / logo.height;
        const height = 64;
        ws.addImage(id, { tl: { col: 0.1, row: 0.1 }, ext: { width: Math.round(height * ratio), height } });
        row = 4;
    }

    const line = (value, font, height) => {
        ws.mergeCells(row, 1, row, width);
        const c = ws.getCell(row, 1);
        c.value = value;
        c.font = { name: FONT, ...font };
        c.alignment = { horizontal: "center", vertical: "middle", wrapText: true };
        ws.getRow(row).height = height;
        row += 1;
    };
    // company, then which report, then its details, then who generated it and when
    const company = companyName();
    if (company) line(company.toUpperCase(), { size: 14, color: { argb: argb(BRAND.text) } }, 22);
    line(String(title).toUpperCase(), { size: 16, bold: true, color: { argb: argb(BRAND.blueDark) } }, 26);
    if (subtitle) line(subtitle, { size: 11, color: { argb: argb(BRAND.muted) } }, 18);
    line(`Generated by ${userName() || "-"} on ${moment().format("DD/MM/YYYY hh:mm A")}`, { size: 9, italic: true, color: { argb: argb(BRAND.muted) } }, 16);

    // a green rule under the header
    for (let c = 1; c <= width; c += 1) ws.getCell(row, c).border = { bottom: { style: "medium", color: { argb: argb(BRAND.green) } } };
    ws.getRow(row).height = 6;

    return { wb, ws, cursor: new SheetCursor(ws, width, row + 2) };
}

class SheetCursor {
    constructor(ws, width, row) {
        this.ws = ws;
        this.width = width;
        this.row = row;
    }

    gap(n = 1) { this.row += n; }

    /** Green band across the sheet: a section title such as "Fees" or "Target 1 · Q1 sales". */
    section(text, { tone = "green" } = {}) {
        const ws = this.ws;
        ws.mergeCells(this.row, 1, this.row, this.width);
        const c = ws.getCell(this.row, 1);
        c.value = text;
        const strong = tone === "green";
        c.font = { name: FONT, size: 12, bold: true, color: { argb: argb(strong ? BRAND.white : BRAND.greenDark) } };
        c.fill = solid(strong ? BRAND.green : BRAND.greenSoft);
        c.alignment = { horizontal: "left", vertical: "middle", indent: 1 };
        ws.getRow(this.row).height = 22;
        this.row += 1;
    }

    /** A line of muted text across the sheet (notes, rules, "no fees"). */
    note(text, { italic = true, color = BRAND.muted, bold = false } = {}) {
        const ws = this.ws;
        ws.mergeCells(this.row, 1, this.row, this.width);
        const c = ws.getCell(this.row, 1);
        c.value = text;
        c.font = { name: FONT, size: 10, italic, bold, color: { argb: argb(color) } };
        c.alignment = { horizontal: "left", vertical: "middle", wrapText: true, indent: 1 };
        const lines = Math.ceil(String(text).length / Math.max(40, this.width * 14));
        ws.getRow(this.row).height = Math.max(18, lines * 15);
        this.row += 1;
    }

    /**
     * Label / value pairs in a grid, `perRow` pairs per line (each pair uses two cells; the
     * last value stretches to the edge). Long values wrap.
     */
    fields(pairs, { perRow = 2 } = {}) {
        const ws = this.ws;
        const span = Math.max(2, Math.floor(this.width / perRow));
        for (let i = 0; i < pairs.length; i += perRow) {
            const line = pairs.slice(i, i + perRow);
            let tallest = 18;
            line.forEach(([label, value], j) => {
                const col = 1 + j * span;
                const lastCol = j === line.length - 1 ? this.width : col + span - 1;
                const l = ws.getCell(this.row, col);
                l.value = label;
                l.font = { name: FONT, size: 10, bold: true, color: { argb: argb(BRAND.text) } };
                l.fill = solid(BRAND.labelBg);
                l.border = gridBorder();
                l.alignment = { vertical: "top", indent: 1 };
                if (lastCol > col + 1) ws.mergeCells(this.row, col + 1, this.row, lastCol);
                const v = ws.getCell(this.row, col + 1);
                v.value = value == null || value === "" ? "-" : value;
                v.font = { name: FONT, size: 10, color: { argb: argb(BRAND.text) } };
                v.alignment = { vertical: "top", wrapText: true, indent: 1 };
                for (let c = col + 1; c <= lastCol; c += 1) ws.getCell(this.row, c).border = gridBorder();
                const chars = String(v.value).length;
                const room = Math.max(10, (lastCol - col) * 14);
                tallest = Math.max(tallest, Math.ceil(chars / room) * 15 + 3);
            });
            ws.getRow(this.row).height = Math.min(tallest, 160);
            this.row += 1;
        }
    }

    /**
     * Grid table: blue header, zebra rows, numbers right-aligned, optional totals row (green).
     * columns: [{ header, key, num, span }] (span: cells the column takes, default 1).
     */
    table(columns, rows, { totals, emptyText = "Nothing to show." } = {}) {
        const ws = this.ws;
        const layout = [];
        let col = 1;
        columns.forEach((c, i) => {
            const span = i === columns.length - 1 ? Math.max(1, this.width - col + 1) : (c.span ?? 1);
            layout.push({ ...c, from: col, to: Math.min(this.width, col + span - 1) });
            col += span;
        });

        const writeRow = (values, style) => {
            let tallest = style.height ?? 18;
            layout.forEach((c) => {
                if (c.to > c.from) ws.mergeCells(this.row, c.from, this.row, c.to);
                const cell = ws.getCell(this.row, c.from);
                const value = values[c.key];
                const number = c.num && !style.header ? toExcelNumber(value) : null;
                cell.value = number ? number.value : value == null ? "" : value;
                if (number) cell.numFmt = number.numFmt;
                cell.font = { name: FONT, size: 10, bold: !!style.bold, color: { argb: argb(style.color ?? BRAND.text) } };
                if (style.fill) cell.fill = solid(style.fill);
                cell.alignment = { horizontal: c.num ? "right" : "left", vertical: "middle", wrapText: true, indent: c.num ? 0 : 1 };
                for (let x = c.from; x <= c.to; x += 1) {
                    const part = ws.getCell(this.row, x);
                    part.border = gridBorder(style.borderColor);
                    if (style.fill) part.fill = solid(style.fill);
                }
                const room = (c.to - c.from + 1) * 13;
                tallest = Math.max(tallest, Math.ceil(String(cell.value).length / Math.max(8, room)) * 15 + 3);
            });
            ws.getRow(this.row).height = Math.min(tallest, 120);
            this.row += 1;
        };

        writeRow(Object.fromEntries(columns.map((c) => [c.key, c.header])), {
            header: true,
            bold: true, color: BRAND.white, fill: BRAND.blue, borderColor: BRAND.blueDark, height: 22,
        });
        if (!rows.length) {
            this.note(emptyText);
            return;
        }
        rows.forEach((r, i) => writeRow(r, {
            fill: r.__tone === "highlight" ? BRAND.greenSoft : r.__tone === "muted" ? BRAND.zebra : i % 2 ? BRAND.zebra : BRAND.white,
            color: r.__tone === "muted" ? BRAND.muted : BRAND.text,
            bold: r.__bold,
        }));
        if (totals) writeRow(totals, { bold: true, fill: BRAND.greenSoft, color: BRAND.greenDark, borderColor: BRAND.green, height: 22 });
    }
}

export async function saveWorkbook(wb, filename) {
    const buffer = await wb.xlsx.writeBuffer();
    const name = `${filename}`.replace(/[/\\?%*:|"<>]/g, "-");
    saveAs(new Blob([buffer], { type: "application/vnd.openxmlformats-officedocument.spreadsheetml.sheet" }), `${name}.xlsx`);
}
